#!/usr/bin/env python3
"""Generate the services bank's tables as Merlin32 source.

  src/svc/gen/font.s    2,048 bytes: a CP437 8x8 font, MSB = leftmost pixel,
                        from Daniel Hepper's public-domain font8x8 (ASCII,
                        Latin-1, Greek, box and block drawing mapped onto the
                        CP437 positions; the rest blank)
  src/svc/gen/tables.s  exp_tab: 256 words, a font row expanded to eight
                        2-bit SHR 640-mode pixels (set = %11, clear = %00),
                        little-endian so a 16-bit store lays the two bytes
                        out left to right
  src/svc/gen/t160.s    the 160x100 mode: t160_cm (a character's two scan
                        lines as SHR 320 pixel masks), t160_bg and t160_d
                        (an attribute's colours spread over four pixels)
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
FONT_DIR = os.path.join(ROOT, "third_party", "font8x8")
OUT_DIR = os.path.join(ROOT, "src", "svc", "gen")

GLYPH = re.compile(r"\{\s*((?:0x[0-9A-Fa-f]{2}\s*,\s*){7}0x[0-9A-Fa-f]{2})\s*\}")


def load(name):
    """All glyphs of a font8x8 header, in order, as 8-byte rows with the
    MSB as the leftmost pixel (font8x8 stores the LSB leftmost)."""
    with open(os.path.join(FONT_DIR, name)) as f:
        text = f.read()
    glyphs = []
    for m in GLYPH.finditer(text):
        rows = [int(x, 16) for x in m.group(1).replace(" ", "").split(",")]
        glyphs.append(bytes(int(f"{r:08b}"[::-1], 2) for r in rows))
    return glyphs


