def unicode_glyph(cp, fonts):
    basic, ext, greek, box, block = fonts
    if cp < 0x80:
        return basic[cp]
    if 0xA0 <= cp <= 0xFF:
        return ext[cp - 0xA0]
    if 0x390 <= cp <= 0x3C9:
        return greek[cp - 0x390]
    if 0x2500 <= cp <= 0x257F:
        return box[cp - 0x2500]
    if 0x2580 <= cp <= 0x259F:
        return block[cp - 0x2580]
    return bytes(8)


def build_font():
    fonts = (load("font8x8_basic.h"), load("font8x8_ext_latin.h"),
             load("font8x8_greek.h"), load("font8x8_box.h"), load("font8x8_block.h"))
    assert len(fonts[0]) == 128 and len(fonts[3]) == 128, [len(f) for f in fonts]
    out = bytearray()
    for code in range(256):
        if 0x20 <= code < 0x7F:
            g = fonts[0][code]
        elif code in CP437:
            g = unicode_glyph(CP437[code], fonts)
        elif code == 0xDB:
            g = bytes([0xFF] * 8)
        else:
            g = bytes(8)
        out += g
    # CP437 0x7F is a house; keep DEL blank from basic. 0xDB full block.
    out[0xDB * 8:0xDB * 8 + 8] = bytes([0xFF] * 8)
    return bytes(out)


def exp_tab():
    words = []
    for b in range(256):
        v = 0
        for i in range(8):                      # i = 0 is the leftmost pixel
            if (b >> (7 - i)) & 1:
                byte, pos = i // 4, 6 - 2 * (i % 4)
                v |= 3 << (pos + 8 * byte)      # byte 0 first in memory
        words.append(v)
    return words


def write_font(font):
    path = os.path.join(OUT_DIR, "font.s")
    with open(path, "w") as f:
        f.write("* font.s - generated by tools/gen_tables.py; do not edit.\n"
                "* CP437 8x8 font, 8 bytes per glyph, MSB = leftmost pixel.\n"
                "* Source: font8x8 by Daniel Hepper (public domain).\n")
        f.write("font\n")
        for i in range(0, 2048, 16):
            f.write(" hex " + font[i:i + 16].hex().upper() + "\n")
        f.write(" err *-font-2048\n")
    return path


# PC/XT keyboard set 1 scan codes by the ASCII the IIGS keyboard delivers.
# Shifted and unshifted characters share a key; control characters map to
# their letter; the special keys (arrows, Delete) are handled in keyboard.s
# before this table.
KEYS = [("1234567890-=", 0x02), ("!@#$%^&*()_+", 0x02), ("qwertyuiop[]", 0x10),
        ("QWERTYUIOP{}", 0x10), ("asdfghjkl;'`", 0x1E), ("ASDFGHJKL:\"~", 0x1E),
        ("\\zxcvbnm,./", 0x2B), ("|ZXCVBNM<>?", 0x2B)]
LETTERS = "qwertyuiop" + "asdfghjkl" + "zxcvbnm"


def scan_tab():
    tab = [0] * 128
    for chars, base in KEYS:
        for i, ch in enumerate(chars):
            tab[ord(ch)] = base + i
    for i in range(1, 27):                       # Ctrl-A .. Ctrl-Z
        tab[i] = tab[ord(chr(ord("a") + i - 1))]
    tab[0x1B], tab[0x09], tab[0x0D], tab[0x08], tab[0x20], tab[0x7F] = 0x01, 0x0F, 0x1C, 0x0E, 0x39, 0x0E
    tab[0x0A] = 0x1C                              # Ctrl-J: Enter's key
    return tab


def write_tables(words):
    path = os.path.join(OUT_DIR, "tables.s")
    with open(path, "w") as f:
        f.write("* tables.s - generated by tools/gen_tables.py; do not edit.\n"
                "* exp_tab: font row byte -> eight 2-bit 640-mode pixels (word).\n")
        f.write("exp_tab\n")
        for i in range(0, 256, 8):
            f.write(" dw " + ",".join(f"${w:04X}" for w in words[i:i + 8]) + "\n")
        f.write(" err *-exp_tab-512\n")
        f.write("* scan_tab: PC scan code for each ASCII code 0-127.\n")
        f.write("scan_tab\n")
        tab = scan_tab()
        for i in range(0, 128, 16):
            f.write(" hex " + "".join(f"{v:02X}" for v in tab[i:i + 16]) + "\n")
        f.write(" err *-scan_tab-128\n")
    return path


