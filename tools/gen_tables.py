def write_dostab():
    path = os.path.join(OUT_DIR, "dostab.s")
    with open(path, "w") as f:
        f.write("* dostab.s - generated by tools/gen_tables.py; do not edit.\n"
                "* int_tab: handler for each interrupt vector (hypercall number 0-255).\n"
                "* dos_tab: handler for each INT 21h function AH = 0-$7F.\n")
        f.write("int_tab\n")
        for i in range(0, 256, 8):
            f.write(" da " + ",".join(f"int_{j:02X}" if j in INTS else "int_default" for j in range(i, i + 8)) + "\n")
        f.write("dos_tab\n")
        for i in range(0, 128, 8):
            f.write(" da " + ",".join(f"dos_{j:02X}" if j in DOS_FUNCS else "dos_unknown" for j in range(i, i + 8)) + "\n")
    return path


def t160_masks(font):
    """The 160x100 mode (docs/cga.md): a cell is two scan lines of its glyph,
    font rows 0 and 1, eight pixels wide on a CGA and four SHR 320 pixels
    here. A pair of font pixels becomes one SHR pixel: foreground when both
    are set, and when one is, on a checkerboard (x + y even), which keeps
    the density of the shade characters. Returns [(row 0, row 1)] of words:
    $F in each nibble that is foreground, the left byte first in memory."""
    out = []
    for ch in range(256):
        rows = []
        for y in range(2):
            b, m = font[ch * 8 + y], 0
            for x in range(4):
                n = (b >> (7 - 2 * x) & 1) + (b >> (6 - 2 * x) & 1)
                if n == 2 or (n == 1 and (x + y) % 2 == 0):
                    m |= 0xF << ((4 - 4 * (x % 2)) + 8 * (x // 2))
            rows.append(m)
        out.append(tuple(rows))
    return out


def write_t160(font):
    path = os.path.join(OUT_DIR, "t160.s")
    with open(path, "w") as f:
        f.write("* t160.s - generated by tools/gen_tables.py; do not edit.\n"
                "* The 160x100 16-colour mode (80x100 text cells of two scan lines).\n"
                "* t160_cm: character -> two words, the foreground mask of the cell's\n"
                "* four SHR 320 pixels on its first and second line (font rows 0, 1).\n")
        f.write("t160_cm\n")
        masks = t160_masks(font)
        for i in range(0, 256, 4):
            f.write(" dw " + ",".join(f"${a:04X},${b:04X}" for a, b in masks[i:i + 4]) + "\n")
        f.write(" err *-t160_cm-1024\n")
        f.write("* t160_bg: attribute -> the background colour in all four pixels.\n")
        f.write("t160_bg\n")
        for i in range(0, 256, 8):
            f.write(" dw " + ",".join(f"${(a >> 4) * 0x1111:04X}" for a in range(i, i + 8)) + "\n")
        f.write(" err *-t160_bg-512\n")
        f.write("* t160_d: attribute -> foreground XOR background in all four pixels:\n"
                "* pixels = (mask AND d) XOR bg.\n")
        f.write("t160_d\n")
        for i in range(0, 256, 8):
            f.write(" dw " + ",".join(f"${((a >> 4) ^ (a & 15)) * 0x1111:04X}" for a in range(i, i + 8)) + "\n")
        f.write(" err *-t160_d-512\n")
        f.write("* t160_row: the row (0-99) a 256-byte page of B800 starts in.\n")
        f.write("t160_row\n")
        rows = bytes(min(p * 256 // 160, 99) for p in range(64))
        for i in range(0, 64, 16):
            f.write(" hex " + rows[i:i + 16].hex().upper() + "\n")
    return path


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    font = build_font()
    print(write_font(font))
    print(write_t160(font))
    print(write_tables(exp_tab()))
    print(write_dostab())


if __name__ == "__main__":
    main()
