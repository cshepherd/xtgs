#!/usr/bin/env python3
"""gen_buildid.py OUT SOURCE...: the build's identity (docs/state.md).

A boot state holds CORE's and SVC's banks as they were, code and variables
together, and is good only for the build that wrote it. BUILD_ID is the
CRC-32 of every source the two images are assembled from, in the order
given (the Makefile's lists); SVC carries it and writes it into the state's
header. OUT is src/svc/gen/buildid.s: generated at every build, not kept.
"""
import sys
import zlib


def main():
    out, sources = sys.argv[1], sys.argv[2:]
    crc = 0
    for path in sources:
        with open(path, "rb") as f:
            crc = zlib.crc32(f.read(), crc)
        crc = zlib.crc32(path.encode(), crc)
    text = ("* buildid.s - generated by tools/gen_buildid.py at every build; do not edit, do not keep.\n"
            f"BUILD_LO   = ${crc & 0xFFFF:04X}\nBUILD_HI   = ${crc >> 16 & 0xFFFF:04X}\n")
    try:
        if open(out).read() == text:
            return
    except OSError:
        pass
    with open(out, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
